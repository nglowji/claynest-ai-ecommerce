import { test, expect } from '@playwright/test'

test('dedicated admin dashboard shows server totals, recent orders and mobile navigation', async ({ page }) => {
  await page.goto('/login')
  await page.getByLabel('Email', { exact: true }).fill(process.env.E2E_ADMIN_EMAIL!)
  await page.getByLabel('Mật khẩu', { exact: true }).fill(process.env.E2E_ADMIN_PASSWORD!)
  await page.getByRole('button', { name: 'Đăng nhập', exact: true }).click()
  await expect(page).toHaveURL('/admin')
  const metrics = page.locator('.dashboard-metrics')
  await expect(metrics).toHaveAttribute('aria-busy', 'false')
  const products = await (await page.request.get('/api/v1/admin/catalog/products?pageSize=1')).json()
  const pending = await (await page.request.get('/api/v1/admin/orders/?status=pending&pageSize=1')).json()
  const stock = await (await page.request.get('/api/v1/admin/inventory/?lowOnly=true&pageSize=1')).json()
  await expect(metrics.getByRole('link').filter({ hasText: 'Tổng sản phẩm' }).locator('strong')).toHaveText(products.totalCount.toLocaleString('vi-VN'))
  await expect(metrics.getByRole('link').filter({ hasText: 'Chờ xác nhận' }).locator('strong')).toHaveText(pending.totalCount.toLocaleString('vi-VN'))
  await expect(metrics.getByRole('link').filter({ hasText: 'Kho cần chú ý' }).locator('strong')).toHaveText(stock.totalCount.toLocaleString('vi-VN'))
  await expect(page.locator('.site-header')).toHaveCount(0)
  await expect(page.locator('.site-footer')).toHaveCount(0)
  await expect(page.getByRole('button', { name: 'Mở tư vấn chọn gốm' })).toHaveCount(0)
  await expect(page.locator('iframe')).toHaveCount(0)
  await page.screenshot({ path: 'test-results/admin-dashboard-desktop.png', fullPage: true })
  await page.setViewportSize({ width: 390, height: 844 })
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth)).toBe(true)
  await page.screenshot({ path: 'test-results/admin-dashboard-mobile.png', fullPage: true })
  await metrics.getByRole('link').filter({ hasText: 'Chờ xác nhận' }).click()
  await expect(page).toHaveURL(/admin\/orders\?status=pending/)
  await expect(page.getByRole('navigation', { name: 'Điều hướng quản trị' }).getByRole('link', { name: 'Đơn hàng' })).toHaveAttribute('aria-current', 'page')
})
