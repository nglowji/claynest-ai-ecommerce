import { readdir, readFile, mkdir, writeFile } from 'node:fs/promises'
import { createHash } from 'node:crypto'
import { resolve, relative, sep } from 'node:path'

const root = resolve('public/images')
const versions = {}
async function scan(directory) {
  for (const entry of (await readdir(directory, { withFileTypes: true })).sort((a, b) => a.name.localeCompare(b.name))) {
    const path = resolve(directory, entry.name)
    if (entry.isDirectory()) await scan(path)
    else if (/\.(jpe?g|png|webp|avif|gif|svg)$/i.test(entry.name)) {
      const url = '/images/' + relative(root, path).split(sep).join('/')
      versions[url] = createHash('sha256').update(await readFile(path)).digest('hex').slice(0, 12)
    }
  }
}
await scan(root)
await mkdir('src/generated', { recursive: true })
await writeFile('src/generated/imageVersions.ts', '// Generated by scripts/image-manifest.mjs.\nexport const imageVersions: Record<string, string> = ' + JSON.stringify(versions, null, 2) + '\n')
